// Turns packages/db/migrations/<dialect>/*.sql into a TypeScript module.
//
// Workers has no filesystem, so `migrate()` cannot read a .sql file at
// runtime on D1 — and a migration runner that works on two of three dialects
// is a trap. The SQL therefore ships as source, generated here and committed,
// exactly as the design tokens are: `test/migrations-bundle.test.ts` fails if
// this output is stale, so the committed file can never drift from the .sql.
//
// Run it after `drizzle-kit generate`:  pnpm --filter @pariksha/db migrations

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
export const PACKAGE_ROOT = join(__dirname, "..");
export const MIGRATIONS_DIR = join(PACKAGE_ROOT, "migrations");
export const OUTPUT_PATH = join(PACKAGE_ROOT, "src/migrations.generated.ts");

/** `sqlite` covers D1 too — same dialect, same files. */
const DIALECTS = ["sqlite", "pg"];

const quote = (value) => JSON.stringify(value);

export function buildModule() {
  const groups = DIALECTS.map((dialect) => {
    const dir = join(MIGRATIONS_DIR, dialect);
    const files = readdirSync(dir)
      .filter((name) => name.endsWith(".sql"))
      .sort();

    const entries = files.map((name) => {
      // Drizzle separates statements with this marker; splitting on it is
      // what lets a driver that takes one statement at a time apply the file.
      const sql = readFileSync(join(dir, name), "utf8");
      const statements = sql
        .split("--> statement-breakpoint")
        .map((s) => s.trim())
        .filter((s) => s.length > 0);
      return `  { name: ${quote(name)}, statements: [\n${statements
        .map((s) => `    ${quote(s)},`)
        .join("\n")}\n  ] },`;
    });

    return `export const ${dialect}Migrations: Migration[] = [\n${entries.join("\n")}\n];`;
  });

  return `// GENERATED by scripts/bundle-migrations.mjs — do not edit.
// Run \`pnpm --filter @pariksha/db migrations\` after changing the schema.

export interface Migration {
  name: string;
  statements: string[];
}

${groups.join("\n\n")}
`;
}

export function writeModule() {
  const contents = buildModule();
  writeFileSync(OUTPUT_PATH, contents);
  return contents;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeModule();
  console.log(`wrote ${OUTPUT_PATH}`);
}
